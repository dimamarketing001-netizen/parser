def _split_top(p):
    """Делит regex по | только на верхнем уровне скобок."""
    parts, depth, cur = [], 0, ""
    for ch in p:
        if ch == "(":
            depth += 1
        elif ch == ")":
            depth -= 1
        if ch == "|" and depth == 0:
            parts.append(cur); cur = ""
        else:
            cur += ch
    parts.append(cur)
    return parts


def _compile():
    """Альтернативы с префиксом ~ — «слабые» (общие слова): срабатывают, только если сильных совпадений нет."""
    strong, weak = [], []
    for p, m, sub in _R:
        alts = _split_top(p)
        # совпадение только с начала слова: иначе «елк» ловится в «отделкой», «бад» в «Баден»
        fix = lambda a: a if a.startswith(("\\b", "^", " ")) else "\\b" + a
        st = [fix(a) for a in alts if not a.startswith("~")]
        wk = [fix(a[1:]) for a in alts if a.startswith("~")]
        if st:
            strong.append((re.compile("|".join(st)), m, sub))
        if wk:
            weak.append((re.compile("|".join(wk)), m, sub))
    return strong, weak


RULES, WEAK_RULES = _compile()

